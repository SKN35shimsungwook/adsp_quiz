OUT_DIR = os.path.join(os.path.dirname(__file__), "data")
OUT_PATH = os.path.join(OUT_DIR, "questions.csv")

# 핵심 문항 하나마다 보기 순서를 바꾼 4개의 변형을 만들어 문제 풀 규모를 늘린다.
# 정답 텍스트를 기준으로 새 인덱스를 다시 계산하므로 항상 정답이 보존된다.
_VARIANT_ORDERS = [
    [0, 1, 2, 3],  # 원본 순서
    [1, 2, 3, 0],  # 1칸 회전
    [2, 3, 0, 1],  # 2칸 회전
    [3, 2, 1, 0],  # 역순
]
_VARIANT_PREFIXES = ["", "", "다음 중 ", "보기 중에서 "]


def _with_prefix(stem, prefix):
    if not prefix or stem.startswith("다음") or stem.startswith("보기"):
        return stem
    return prefix + stem


def expand(q, core_id):
    """핵심 문항 하나를 보기 순서·문구가 다른 4개의 문항으로 확장한다.
    core_id는 같은 원본 문항에서 나온 변형들을 묶어주는 식별자로,
    한 퀴즈 세션에서 같은 개념이 중복 출제되지 않도록 하는 데 사용된다."""
    correct_text = q["c"][q["a"]]
    variants = []
    for order, prefix in zip(_VARIANT_ORDERS, _VARIANT_PREFIXES):
        new_choices = [q["c"][i] for i in order]
        variants.append({
            "s": q["s"],
            "t": q["t"],
            "q": _with_prefix(q["q"], prefix),
            "c": new_choices,
            "a": new_choices.index(correct_text),
            "e": q["e"],
            "core_id": core_id,
        })
    return variants


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    expanded = []
    for core_id, q in enumerate(QUESTIONS, start=1):
        expanded.extend(expand(q, core_id))

    with open(OUT_PATH, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow([
            "id", "subject", "tag", "question",
            "choice1", "choice2", "choice3", "choice4",
            "answer", "explanation", "core_id", "source",
        ])
        for i, q in enumerate(expanded, start=1):
            writer.writerow([
                i, q["s"], q["t"], q["q"],
                q["c"][0], q["c"][1], q["c"][2], q["c"][3],
                q["a"] + 1,
                q["e"],
                q["core_id"],
                "concept",
            ])
    print(f"core questions: {len(QUESTIONS)} -> expanded rows: {len(expanded)} -> {OUT_PATH}")


if __name__ == "__main__":
    main()
